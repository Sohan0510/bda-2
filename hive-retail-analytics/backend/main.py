@app.get("/api/hive/scripts")
def get_hive_scripts() -> List[Dict[str, Any]]:
    """Return list and content of all HiveQL scripts in the project."""
    if not HIVE_DIR.exists():
        return []
    scripts = []
    for p in sorted(HIVE_DIR.glob("*.hql")):
        try:
            content = p.read_text(encoding="utf-8")
            scripts.append(
                {
                    "name": p.name,
                    "lines": len(content.splitlines()),
                    "size_bytes": p.stat().st_size,
                    "code": content,
                }
            )
        except Exception as exc:
            scripts.append({"name": p.name, "error": str(exc)})
    return scripts


@app.post("/api/hive/run-validation")
def trigger_validation() -> Dict[str, Any]:
    """Trigger independent verification re-run and return updated results."""
    validate_script = ROOT / "tests" / "validate.py"
    if not validate_script.exists():
        raise HTTPException(status_code=500, detail="validate.py script missing")
    try:
        proc = subprocess.run([sys.executable, str(validate_script)], capture_output=True, text=True, check=False)
        updated = load_json(VALIDATION_DIR / "validation_results.json")
        return {
            "success": proc.returncode == 0,
            "stdout": proc.stdout,
            "stderr": proc.stderr,
            "results": updated,
        }
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))


