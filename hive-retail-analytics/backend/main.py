@app.get("/api/products/catalog")
def get_product_catalog(
    q: Optional[str] = None,
    sort_by: str = Query("quantity", regex="^(quantity|revenue|invoices|description)$"),
    order: str = Query("desc", regex="^(asc|desc)$"),
    page: int = Query(1, ge=1),
    page_size: int = Query(25, ge=1, le=100),
) -> Dict[str, Any]:
    """Searchable, paginated product catalog across all 4,070 items."""
    df = load_tsv("c_product_quantity_all")
    if df.empty:
        raise HTTPException(status_code=404, detail="Product catalog not found")

    df["total_quantity"] = pd.to_numeric(df["total_quantity"], errors="coerce").fillna(0)
    df["total_sales_value_gbp"] = pd.to_numeric(df["total_sales_value_gbp"], errors="coerce").fillna(0)
    df["distinct_invoices"] = pd.to_numeric(df["distinct_invoices"], errors="coerce").fillna(0)

    if q:
        query_str = q.strip().lower()
        df = df[
            df["stockcode"].str.lower().str.contains(query_str, na=False)
            | df["description"].str.lower().str.contains(query_str, na=False)
        ]

    sort_col_map = {
        "quantity": "total_quantity",
        "revenue": "total_sales_value_gbp",
        "invoices": "distinct_invoices",
        "description": "description",
    }
    col = sort_col_map.get(sort_by, "total_quantity")
    ascending = order == "asc"
    df = df.sort_values(by=col, ascending=ascending)

    total_items = len(df)
    total_pages = max(1, (total_items + page_size - 1) // page_size)
    offset = (page - 1) * page_size
    paged_df = df.iloc[offset : offset + page_size]

    return {
        "total": total_items,
        "page": page,
        "page_size": page_size,
        "total_pages": total_pages,
        "items": paged_df.to_dict(orient="records"),
    }


