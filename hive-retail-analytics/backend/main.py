@app.get("/api/monthly-sales")
def get_monthly_sales() -> Dict[str, Any]:
    """Return monthly sales velocity, unit volumes, and signed revenue."""
    df = load_tsv("b_monthly_sales")
    if df.empty:
        raise HTTPException(status_code=404, detail="Monthly sales data not available")

    for col in [
        "transaction_lines",
        "distinct_invoices",
        "quantity_sold",
        "positive_sales_quantity",
        "signed_revenue_gbp",
        "positive_sales_revenue_gbp",
        "cancellation_adjustment_gbp",
        "avg_positive_line_value_gbp",
    ]:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    records = df.to_dict(orient="records")
    peak_month = max(records, key=lambda x: x.get("positive_sales_revenue_gbp", 0))
    low_month = min(records, key=lambda x: x.get("positive_sales_revenue_gbp", 0))
    avg_rev = sum(r.get("positive_sales_revenue_gbp", 0) for r in records) / len(records)

    return {
        "count": len(records),
        "peak_month": peak_month,
        "lowest_month": low_month,
        "average_monthly_revenue_gbp": round(avg_rev, 2),
        "data": records,
    }


