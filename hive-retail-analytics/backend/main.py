@app.get("/api/countries/summary")
def get_countries_summary() -> Dict[str, Any]:
    """Return country-level sales, identified customers, and UK vs export distribution."""
    df = load_tsv("e_country_summary")
    if df.empty:
        raise HTTPException(status_code=404, detail="Country summary not found")

    for col in ["transaction_lines", "distinct_invoices", "identified_customers", "quantity_sold", "revenue_gbp"]:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    records = df.sort_values(by="revenue_gbp", ascending=False).to_dict(orient="records")
    uk_record = next((r for r in records if r["country"] == "United Kingdom"), None)
    total_revenue = sum(r["revenue_gbp"] for r in records)
    uk_rev = uk_record["revenue_gbp"] if uk_record else 0
    uk_share_pct = round((uk_rev / total_revenue) * 100, 2) if total_revenue else 0

    return {
        "total_countries": len(records),
        "total_revenue_gbp": round(total_revenue, 2),
        "uk_share_percentage": uk_share_pct,
        "countries": records,
    }


