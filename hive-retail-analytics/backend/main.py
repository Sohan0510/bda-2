# Helper Functions for TSV / JSON Loading
# -----------------------------------------------------------------------------
def load_tsv(name: str) -> pd.DataFrame:
    """Load a TSV output generated by Apache Hive into a clean Pandas DataFrame."""
    path = OUTPUTS_DIR / f"{name}.tsv"
    if not path.exists():
        return pd.DataFrame()
    try:
        df = pd.read_csv(path, sep="\t", dtype=str, encoding="utf-8", encoding_errors="replace")
        df.columns = [c.strip().lower() for c in df.columns]
        df = df[df.astype(str).apply(lambda r: (r.str.len() > 0).any(), axis=1)].reset_index(drop=True)
        return df
    except Exception as exc:
        print(f"Error reading {name}.tsv: {exc}", file=sys.stderr)
        return pd.DataFrame()


def load_json(path: Path) -> dict:
    if path.exists():
        try:
            with open(path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as exc:
            print(f"Error reading JSON {path}: {exc}", file=sys.stderr)
    return {}


